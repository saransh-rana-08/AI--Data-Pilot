import React, { createContext, useContext, useState, useEffect, useCallback } from 'react';
import { initialDatabaseConfig, mockTables, mockSampleQueries } from '../data/mockDatabase';
import { synthesizeSQLFromPrompt, AI_GENERATION_STEPS } from '../services/sqlGenerator';
import { 
  testConnection, 
  fetchDatabaseSchema, 
  executeSQLQuery, 
  saveAndConnectDatabase, 
  fetchCurrentConnection,
  disconnectDatabaseAPI,
  generateAISQL,
  fetchAIConfig,
  updateAIConfig
} from '../services/api';

const DatabaseContext = createContext();

export function DatabaseProvider({ children }) {
  const [currentView, setCurrentView] = useState('dashboard');
  const [dbConfig, setDbConfig] = useState(initialDatabaseConfig);
  const [tables, setTables] = useState(mockTables);
  const [historyList, setHistoryList] = useState(mockSampleQueries);

  // AI & Groq Configuration state
  const [aiConfig, setAiConfig] = useState({
    has_api_key: false,
    model: 'openai/gpt-oss-120b',
    available_models: []
  });

  // Active query state
  const [queryPrompt, setQueryPrompt] = useState('Show the top 5 students by CGPA');
  const [activeQuery, setActiveQuery] = useState(mockSampleQueries[0]);
  const [isGenerating, setIsGenerating] = useState(false);
  const [generationStep, setGenerationStep] = useState(0);

  // Modals & UI states
  const [isConnectionModalOpen, setIsConnectionModalOpen] = useState(false);
  const [isCommandPaletteOpen, setIsCommandPaletteOpen] = useState(false);
  const [toasts, setToasts] = useState([]);

  // Toast notification helper (memoized)
  const addToast = useCallback((title, message = '', type = 'info') => {
    const id = Date.now() + Math.random().toString(36).substring(2, 6);
    setToasts(prev => [...prev, { id, title, message, type }]);
    setTimeout(() => {
      setToasts(prev => prev.filter(t => t.id !== id));
    }, 4000);
  }, []);

  const removeToast = useCallback((id) => {
    setToasts(prev => prev.filter(t => t.id !== id));
  }, []);

  // Keyboard shortcut listener for Ctrl+K / Cmd+K
  useEffect(() => {
    const handleKeyDown = (e) => {
      if ((e.metaKey || e.ctrlKey) && e.key === 'k') {
        e.preventDefault();
        setIsCommandPaletteOpen(prev => !prev);
      }
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, []);

  // Navigation helper
  const navigate = (view, extraState = {}) => {
    setCurrentView(view);
    if (extraState.prompt !== undefined) {
      setQueryPrompt(extraState.prompt);
    }
    if (extraState.runImmediately && extraState.prompt) {
      executeAiGeneration(extraState.prompt);
    }
  };

  // AI query generation using LangChain + Groq
  const executeAiGeneration = async (promptToRun) => {
    if (!dbConfig.connected) {
      addToast('No Database Connected', 'Please connect a database before asking queries.', 'error');
      setIsConnectionModalOpen(true);
      return;
    }

    const trimmed = (promptToRun || queryPrompt).trim();
    if (!trimmed) return;

    setIsGenerating(true);
    setGenerationStep(0);

    const step1Timer = setTimeout(() => setGenerationStep(1), 350);
    const step2Timer = setTimeout(() => setGenerationStep(2), 700);

    try {
      // 1. Request real-time SQL generation via FastAPI + LangChain Groq
      const res = await generateAISQL(trimmed, {
        model: aiConfig.model,
      });

      clearTimeout(step1Timer);
      clearTimeout(step2Timer);

      const exec = res.execution_result;
      let finalColumns = [];
      let finalRows = [];
      let isSuccess = res.success && (!exec || exec.success);
      let errMsg = exec && !exec.success ? exec.error : null;

      if (exec && exec.columns) {
        finalColumns = exec.columns;
        finalRows = (exec.rows || []).map(row => {
          const obj = {};
          exec.columns.forEach((col, idx) => {
            obj[col] = row[idx];
          });
          return obj;
        });
      }

      const newQueryItem = {
        id: 'q-' + Date.now(),
        prompt: trimmed,
        sql: res.sql,
        explanation: res.explanation,
        executionTime: exec ? `${exec.execution_time_ms} ms` : '40 ms',
        rowCount: exec ? exec.row_count : finalRows.length,
        status: isSuccess ? 'Success' : 'Failed',
        errorMessage: errMsg,
        columns: finalColumns,
        rows: finalRows,
        timestamp: 'Just now',
        model: res.model
      };

      setActiveQuery(newQueryItem);
      setHistoryList(prev => [newQueryItem, ...prev]);
      setIsGenerating(false);

      if (isSuccess) {
        addToast('SQL Generated by Groq', `${newQueryItem.rowCount} rows returned (${newQueryItem.executionTime})`, 'success');
      } else {
        addToast('Execution Notice', errMsg || 'Query generated but execution returned no rows or an error.', 'warning');
      }

    } catch (err) {
      clearTimeout(step1Timer);
      clearTimeout(step2Timer);

      console.warn('AI SQL generation failed, attempting live database execution fallback:', err);
      const isMissingKey = err.message?.toLowerCase().includes('groq api key is not configured');

      // If database is connected, attempt heuristic SQL directly against the live database
      if (dbConfig.connected && tables.length > 0) {
        const isPostgres = (dbConfig.type || '').toLowerCase().includes('postgres');
        const quote = isPostgres ? '"' : '`';
        const norm = trimmed.toLowerCase();

        // Match table
        let targetTable = tables.find(t => norm.includes(t.name.toLowerCase()));
        if (!targetTable) {
          targetTable = tables.find(t => norm.includes(t.name.toLowerCase().replace(/s$/, ''))) || tables[0];
        }

        const tableName = `${quote}${targetTable.name}${quote}`;
        const cols = targetTable.columns || [];

        // Build simple WHERE clause from prompt
        let conditions = [];
        for (const col of cols) {
          const colNameLower = col.name.toLowerCase();
          if (norm.includes(colNameLower)) {
            const ltMatch = norm.match(new RegExp(`${colNameLower}\\s*(?:is\\s*)?(?:less than|<|under|below)\\s*(\\d+(?:\\.\\d+)?)`));
            const gtMatch = norm.match(new RegExp(`${colNameLower}\\s*(?:is\\s*)?(?:greater than|>|above|over|more than)\\s*(\\d+(?:\\.\\d+)?)`));
            const eqMatch = norm.match(new RegExp(`${colNameLower}\\s*(?:is|=|equals?)\\s*['"]?([a-zA-Z0-9_-]+)['"]?`));

            if (ltMatch) {
              conditions.push(`${quote}${col.name}${quote} < ${ltMatch[1]}`);
            } else if (gtMatch) {
              conditions.push(`${quote}${col.name}${quote} > ${gtMatch[1]}`);
            } else if (eqMatch && !['less', 'greater', 'more', 'under'].includes(eqMatch[1])) {
              const val = isNaN(eqMatch[1]) ? `'${eqMatch[1]}'` : eqMatch[1];
              conditions.push(`${quote}${col.name}${quote} = ${val}`);
            }
          }
        }

        // Check if "less than 30" or similar refers to age even if formatted loosely
        if (conditions.length === 0 && norm.includes('age')) {
          const ageMatch = norm.match(/(?:less than|<|under|below)\s*(\d+)/);
          if (ageMatch) {
            const ageCol = cols.find(c => c.name.toLowerCase() === 'age');
            if (ageCol) {
              conditions.push(`${quote}${ageCol.name}${quote} < ${ageMatch[1]}`);
            }
          }
        }

        const whereStr = conditions.length > 0 ? ` WHERE ${conditions.join(' AND ')}` : '';
        const fallbackSql = `SELECT * FROM ${tableName}${whereStr} LIMIT 50;`;

        try {
          const liveExec = await executeSQLQuery(fallbackSql);
          const finalRows = (liveExec.rows || []).map(row => {
            const obj = {};
            liveExec.columns.forEach((col, idx) => {
              obj[col] = row[idx];
            });
            return obj;
          });

          const newQueryItem = {
            id: 'q-' + Date.now(),
            prompt: trimmed,
            sql: fallbackSql,
            explanation: `Retrieved records from ${targetTable.name} in ${dbConfig.name}.`,
            executionTime: `${liveExec.execution_time_ms} ms`,
            rowCount: liveExec.row_count,
            status: 'Success',
            errorMessage: null,
            columns: liveExec.columns,
            rows: finalRows,
            timestamp: 'Just now',
            model: 'Live DB Engine',
            database: dbConfig.name
          };

          setActiveQuery(newQueryItem);
          setHistoryList(prev => [newQueryItem, ...prev]);
          setIsGenerating(false);

          if (isMissingKey) {
            addToast('Executed Live DB Query', `Fetched ${liveExec.row_count} rows from ${targetTable.name} (Configure Groq in Settings for complex questions)`, 'info');
          } else {
            addToast('Executed Live DB Query', `Fetched ${liveExec.row_count} rows from ${targetTable.name}`, 'success');
          }
          return;
        } catch (dbErr) {
          console.error('Fallback query execution failed:', dbErr);
        }
      }

      // If cannot execute on live DB, display failure error on real context, NEVER mock students
      const failedItem = {
        id: 'q-' + Date.now(),
        prompt: trimmed,
        sql: `-- Query synthesis failed for prompt: ${trimmed}\n-- Error: ${err.message}`,
        executionTime: '0 ms',
        rowCount: 0,
        status: 'Failed',
        errorMessage: err.message || 'Failed to synthesize and execute SQL',
        columns: [],
        rows: [],
        timestamp: 'Just now',
        model: 'Error',
        database: dbConfig.name
      };

      setActiveQuery(failedItem);
      setHistoryList(prev => [failedItem, ...prev]);
      setIsGenerating(false);

      if (isMissingKey) {
        addToast('Groq Key Required', 'Set your GROQ_API_KEY in Settings to enable live LLM generation.', 'warning');
      } else {
        addToast('Query Failed', err.message || 'Could not generate SQL for prompt', 'error');
      }
    }
  };

  // Load database metadata and tables from FastAPI backend
  const loadDatabaseFromBackend = useCallback(async (silent = false) => {
    try {
      const conn = await testConnection();
      if (!conn || !conn.success) {
        setDbConfig(prev => ({ ...prev, connected: false }));
        setTables([]);
        return false;
      }

      let currentConn = null;
      try {
        currentConn = await fetchCurrentConnection();
      } catch (e) {
        console.warn('Could not fetch current connection:', e);
      }

      const rawType = currentConn?.db_type || 'mysql';
      const isPostgres = rawType.toLowerCase().includes('postgr');
      const formattedType = isPostgres ? 'PostgreSQL' : 'MySQL';
      const quote = isPostgres ? '"' : '`';

      const schema = await fetchDatabaseSchema();
      if (!schema || !schema.tables) {
        setDbConfig(prev => ({ ...prev, connected: false }));
        setTables([]);
        return false;
      }

      // Transform tables into the structure TableSchemaView expects
      const transformedTables = await Promise.all(
        schema.tables.map(async (table) => {
          let sampleData = [];
          let rowCount = 0;

          try {
            // Fetch preview data and count with dialect-safe identifier quoting
            const previewRes = await executeSQLQuery(`SELECT * FROM ${quote}${table.name}${quote} LIMIT 10`);
            if (previewRes.success && previewRes.rows) {
              sampleData = previewRes.rows.map(row => {
                const obj = {};
                previewRes.columns.forEach((col, idx) => {
                  obj[col] = row[idx];
                });
                return obj;
              });
              rowCount = previewRes.row_count;
            }

            const countRes = await executeSQLQuery(`SELECT COUNT(*) as cnt FROM ${quote}${table.name}${quote}`);
            if (countRes.success && countRes.rows && countRes.rows.length > 0) {
              rowCount = countRes.rows[0][0];
            }
          } catch (e) {
            console.warn(`Could not load preview for table ${table.name}:`, e);
          }

          const columns = table.columns.map(col => {
            const isPrimary = table.primary_keys.includes(col.name);
            const fk = table.foreign_keys.find(f => f.constrained_columns.includes(col.name));
            const isForeign = Boolean(fk);
            const references = fk ? `${fk.referred_table}.${fk.referred_columns[0] || 'id'}` : null;

            return {
              name: col.name,
              type: col.type,
              isPrimary,
              isForeign,
              references,
              nullable: col.nullable,
              defaultVal: col.default,
            };
          });

          return {
            name: table.name,
            description: `${formattedType} table: ${table.name}`,
            rowCount: Number(rowCount),
            columnsCount: columns.length,
            columns,
            sampleData,
          };
        })
      );

      setTables(transformedTables);

      const totalCols = transformedTables.reduce((acc, t) => acc + t.columnsCount, 0);
      const totalFks = schema.tables.reduce((acc, t) => acc + (t.foreign_keys?.length || 0), 0);
      const totalRows = transformedTables.reduce((acc, t) => acc + (t.rowCount || 0), 0);

      setDbConfig(prev => ({
        ...prev,
        connected: true,
        name: schema.database || currentConn?.database || 'defaultdb',
        type: formattedType,
        version: isPostgres ? '15+' : '8.0',
        host: currentConn?.host || 'localhost',
        port: String(currentConn?.port || (isPostgres ? 5432 : 3306)),
        user: currentConn?.user || 'avnadmin',
        ssl_mode: currentConn?.ssl_mode || 'REQUIRED',
        connectedAt: 'Just now',
        totalTables: transformedTables.length,
        totalColumns: totalCols,
        totalRelationships: totalFks,
        totalRows: totalRows.toLocaleString(),
        size: 'Cloud Database',
      }));

      // Set initial sample query on real table if currently targeting unmapped table
      if (transformedTables.length > 0) {
        const firstTable = transformedTables[0];
        setQueryPrompt(`customer with age less than 30`);
        if (firstTable.sampleData && firstTable.sampleData.length > 0) {
          const sampleCols = firstTable.columns.map(c => c.name);
          setActiveQuery({
            id: 'q-init',
            prompt: `SELECT * FROM ${quote}${firstTable.name}${quote} LIMIT 10`,
            sql: `SELECT * FROM ${quote}${firstTable.name}${quote} LIMIT 10;`,
            explanation: `Initial preview from ${firstTable.name} in ${schema.database || currentConn?.database || 'customer'}.`,
            executionTime: '28 ms',
            rowCount: firstTable.sampleData.length,
            status: 'Success',
            errorMessage: null,
            columns: sampleCols,
            rows: firstTable.sampleData,
            timestamp: 'Just now',
            model: 'Live Schema Preview',
            database: schema.database || currentConn?.database || 'customer'
          });
        }
      }

      if (!silent) {
        addToast('Database Synced', `Connected to ${formattedType} (${transformedTables.length} tables found)`, 'success');
      }

      return true;
    } catch (err) {
      console.warn('Could not auto-connect to backend database:', err);
      setDbConfig(prev => ({ ...prev, connected: false }));
      setTables([]);
      return false;
    }
  }, [addToast]);

  // Load AI configuration from backend
  const loadAIConfig = useCallback(async () => {
    try {
      const data = await fetchAIConfig();
      setAiConfig(data);
    } catch (e) {
      console.warn('Could not load AI configuration:', e);
    }
  }, []);

  const saveAiConfig = async (apiKey, model) => {
    try {
      const res = await updateAIConfig({ api_key: apiKey, model });
      setAiConfig(prev => ({
        ...prev,
        has_api_key: res.has_api_key,
        model: res.model
      }));
      addToast('AI Configuration Saved', `Groq model set to ${res.model}`, 'success');
      return true;
    } catch (e) {
      addToast('Config Save Failed', e.message, 'error');
      return false;
    }
  };

  // Initial auto-sync with backend on mount
  useEffect(() => {
    loadDatabaseFromBackend(true);
    loadAIConfig();
  }, [loadDatabaseFromBackend, loadAIConfig]);

  // Re-run an edited SQL statement using live backend execution
  const reRunSQL = async (sqlText) => {
    if (!dbConfig.connected) {
      addToast('Error', 'Database disconnected', 'error');
      return;
    }

    const queryToRun = (sqlText || activeQuery?.sql || '').trim();
    if (!queryToRun) return;

    try {
      const data = await executeSQLQuery(queryToRun);
      const objectRows = (data.rows || []).map(row => {
        const obj = {};
        data.columns.forEach((col, idx) => {
          obj[col] = row[idx];
        });
        return obj;
      });

      const updatedQuery = {
        id: 'q-' + Date.now(),
        prompt: activeQuery?.prompt || queryToRun,
        sql: queryToRun,
        executionTime: `${data.execution_time_ms} ms`,
        rowCount: data.row_count,
        status: 'Success',
        errorMessage: null,
        columns: data.columns,
        rows: objectRows,
        timestamp: 'Just now'
      };

      setActiveQuery(updatedQuery);
      setHistoryList(prev => [updatedQuery, ...prev]);
      addToast('Query Executed', `${data.row_count} rows returned in ${data.execution_time_ms} ms`, 'success');
    } catch (err) {
      const failedQuery = {
        id: 'q-' + Date.now(),
        prompt: activeQuery?.prompt || queryToRun,
        sql: queryToRun,
        executionTime: '0 ms',
        rowCount: 0,
        status: 'Failed',
        errorMessage: err.message,
        columns: [],
        rows: [],
        timestamp: 'Just now'
      };
      setActiveQuery(failedQuery);
      addToast('Query Failed', err.message, 'error');
    }
  };

  // Reset / clear query workspace
  const clearQuery = () => {
    setQueryPrompt('');
    setActiveQuery(null);
  };

  // Connect database with dynamic parameters
  const connectDatabase = async (newConfig) => {
    setIsConnectionModalOpen(false);
    if (newConfig && newConfig.host && (newConfig.name || newConfig.database)) {
      try {
        const isPg = (newConfig.type || newConfig.db_type || '').toLowerCase().includes('postgr');
        await saveAndConnectDatabase({
          db_type: isPg ? 'postgresql' : 'mysql',
          host: newConfig.host,
          port: Number(newConfig.port) || (isPg ? 5432 : 3306),
          database: newConfig.name || newConfig.database,
          user: newConfig.user,
          password: newConfig.password || '',
          ssl_mode: newConfig.ssl_mode || 'REQUIRED'
        });
        addToast('Connected Successfully', `Connected to ${newConfig.name || newConfig.database}`, 'success');
      } catch (err) {
        addToast('Connection Failed', err.message, 'error');
        return false;
      }
    }
    const synced = await loadDatabaseFromBackend(false);
    return synced;
  };

  // Disconnect database (both frontend and backend)
  const disconnectDatabase = async () => {
    try {
      await disconnectDatabaseAPI();
    } catch (e) {
      console.warn('Backend disconnect error:', e);
    }

    setDbConfig({
      connected: false,
      name: 'No Database',
      type: 'None',
      version: '',
      host: '',
      port: '',
      user: '',
      ssl_mode: 'DISABLED',
      connectedAt: '',
      totalTables: 0,
      totalColumns: 0,
      totalRelationships: 0,
      totalRows: '0',
      size: '0 KB',
    });
    setTables([]);
    setActiveQuery(null);
    setQueryPrompt('');
    setIsConnectionModalOpen(false);
    addToast('Database Disconnected', 'Connection closed successfully.', 'info');
  };

  return (
    <DatabaseContext.Provider
      value={{
        currentView,
        setCurrentView,
        navigate,
        dbConfig,
        setDbConfig,
        tables,
        historyList,
        queryPrompt,
        setQueryPrompt,
        activeQuery,
        setActiveQuery,
        isGenerating,
        generationStep,
        generationSteps: AI_GENERATION_STEPS,
        executeAiGeneration,
        reRunSQL,
        refreshDatabase: () => loadDatabaseFromBackend(false),
        clearQuery,
        isConnectionModalOpen,
        setIsConnectionModalOpen,
        isCommandPaletteOpen,
        setIsCommandPaletteOpen,
        toasts,
        addToast,
        removeToast,
        connectDatabase,
        disconnectDatabase,
        aiConfig,
        setAiConfig,
        saveAiConfig,
        loadAIConfig,
      }}
    >
      {children}
    </DatabaseContext.Provider>
  );
}

export function useDatabase() {
  const context = useContext(DatabaseContext);
  if (!context) {
    throw new Error('useDatabase must be used within a DatabaseProvider');
  }
  return context;
}
